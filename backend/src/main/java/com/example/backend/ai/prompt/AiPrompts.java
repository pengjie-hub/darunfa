package com.example.backend.ai.prompt;

/**
 * 全部 AI 系统提示词（Prompt 模板的集中管理点）。
 *
 * <h3>为什么集中放一个类</h3>
 * 提示词是这个系统里最容易被反复调优、也最需要被评审的东西。集中在一个类里：
 * <ul>
 *   <li>调优时不必在 7 个服务文件之间跳转，改动可一次性 review；</li>
 *   <li>业务规则（GMV 口径、只读约束、口径一致性）不会被散落在各处的字符串拼接淹没；</li>
 *   <li>与「模型配置」「工具定义」「记忆存储」并列成四个正交的关注点。</li>
 * </ul>
 *
 * <h3>模板变量语法</h3>
 * 采用 LangChain4j / Mustache 风格的双花括号 {@code {{变量名}}}，与
 * {@code @AiService} 方法上的 {@code @V("变量名")} 参数一一对应。
 * <b>注意</b>：单个花括号（例如 JSON 示例 {@code {"a":"b"}}）是普通字符，不会被解析，
 * 因此提示词里的 JSON 样例可以原样书写。
 */
